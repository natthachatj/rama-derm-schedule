"""Tokenize stylesheet colors by use, retaining exact light colors and supplying dark equivalents."""
from pathlib import Path
import re,colorsys
root=Path(__file__).resolve().parent.parent
palette={}
def dark(color,role):
 raw=color.lstrip('#');raw=''.join(c*2 for c in raw) if len(raw) in (3,4) else raw
 if len(raw) not in (6,8):return color
 rgb=tuple(int(raw[i:i+2],16)/255 for i in (0,2,4));h,l,s=colorsys.rgb_to_hls(*rgb)
 if role=='bg':
  if l>.75:
   if s<.1:h=.6;s=.32
   l=.15+(1-l)*.22;s=min(s,.38)
  elif l>.5 and s<.3:l=.23
 elif role=='border':l=.31 if l>.65 else max(.28,l);s=min(s,.4)
 elif role=='fg':
  if l<.3:l=.9 if l<.18 else .84;s=min(s,.55)
  elif l<.82:l=max(.73,l);s=min(s,.7)
 r,g,b=colorsys.hls_to_rgb(h,l,s);return '#'+''.join(f'{round(v*255):02x}' for v in (r,g,b))+raw[6:]
for name in ['app/globals.css','app/clinical/clinical.css']:
 p=root/name;text=p.read_text();text=re.sub(r'var\(--theme-(?:bg|fg|border|shadow)-[0-9a-f]+,(#[0-9a-fA-F]{3,8})\)',r'\1',text)
 def declaration(m):
  prop,value=m.group(1),m.group(2)
  value=re.sub(r'\bwhite\b','#fff',value);value=re.sub(r'\bblack\b','#000',value)
  role='border' if 'border' in prop or prop=='--border' else 'shadow' if 'shadow' in prop else 'bg' if any(k in prop for k in ['background','--bg','-bg-']) else 'fg'
  def color(c):
   literal=c.group();key='--theme-'+role+'-'+literal[1:].lower();palette[key]=dark(literal,role);return 'var('+key+','+literal+')'
  return prop+':'+re.sub(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{4}\b|#[0-9a-fA-F]{3}\b',color,value)
 text=re.sub(r'([\w-]+):([^;{}]+)',declaration,text);p.write_text(text)
out='/* Generated by scripts/theme-palette.py; light colors remain the stylesheet defaults. */\n:root[data-theme="dark"]{\n'+''.join(f' {k}:{v};\n' for k,v in sorted(palette.items()))+'}\n'
out+='''html[data-theme="dark"] body{background:#142235;color:#e4edf9}
html[data-theme="dark"] .sidebar{background:#101e36;color:#d5e3f6}
html[data-theme="dark"] .sidebar .side-label,html[data-theme="dark"] .sidebar .side-bottom{color:#adbed6}
html[data-theme="dark"] .sidebar nav button.active{background:#233e67;color:#f3f7ff}
html[data-theme="dark"] .button.primary,html[data-theme="dark"] .tab.active{background:#3767c5;color:#fff}
html[data-theme="dark"] .hero{background:#122d4d;color:#edf5ff}
html[data-theme="dark"] .hero h2,html[data-theme="dark"] .hero p{color:#edf5ff}
html[data-theme="dark"] .fc{--fc-border-color:#3b506b;--fc-neutral-bg-color:#20344d;--fc-page-bg-color:#1c2d43;--fc-today-bg-color:#28486b;--fc-list-event-hover-bg-color:#294261;color:#e4edf9}
html[data-theme="dark"] input,html[data-theme="dark"] select,html[data-theme="dark"] textarea{color-scheme:dark}
html[data-theme="dark"] .clinical-dashboard-stats strong,html[data-theme="dark"] .clinical-color-chart h3,html[data-theme="dark"] .clinical-card-header strong{color:#e1eeff}
html[data-theme="dark"] .clinical-facial-reference img{background:#fff}
html[data-theme="dark"] .clinical-color-chart svg text{fill:#dce9fa}
html[data-theme="dark"] .presentation-signature{background:#fff}
@media print{html[data-theme="dark"]{color-scheme:light}html[data-theme="dark"] body{background:#fff;color:#172940}}
'''
(root/'app/theme-palette.css').write_text(out)
print(f'{len(palette)} theme colors generated')
